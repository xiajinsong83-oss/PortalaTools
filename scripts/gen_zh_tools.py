def render_intro(paras):
    return "\n\n".join(paras) + "\n"

errors = []
count = 0
for f in sorted(glob.glob(os.path.join(SRC, "*.md"))):
    slug = os.path.basename(f)[:-3]
    if slug == "_index":
        continue
    if slug not in TR:
        errors.append(slug)
        continue
    text = open(f, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        errors.append(slug + " (no front matter)")
        continue
    fm, body = m.group(1), m.group(2)

    title, desc, paras = TR[slug]

    # body tail: everything from the first ad-unit shortcode onward (UI block)
    idx = body.find("{{< ad-unit >}}")
    if idx == -1:
        errors.append(slug + " (no ad-unit)")
        continue
    ui_block = body[idx:]

    # preserve date/lastmod from the EN front matter
    date = re.search(r'date:\s*([0-9-]+)', fm)
    lastmod = re.search(r'lastmod:\s*([0-9-]+)', fm)
    date_s = date.group(1) if date else "2026-10-02"
    lastmod_s = lastmod.group(1) if lastmod else date_s

    zh = (
        "---\n"
        f'title: "{title}"\n'
        f"date: {date_s}\n"
        f"lastmod: {lastmod_s}\n"
        f'description: "{desc}"\n'
        f"slug: {slug}\n"
        f'canonicalURL: "https://portalaser.cn/zh/tools/{slug}/"\n'
        "showToc: false\n"
        "---\n\n"
        + render_intro(paras)
        + ui_block
    )
    out = os.path.join(DST, slug + ".md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(zh)
    count += 1

print(f"generated: {count}")
if errors:
    print("MISSING:", errors)
